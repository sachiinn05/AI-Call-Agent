/**
 * Turns "this reply was bad" reports into things you can commit: regression tests for the
 * conversation engine, and Q&A lines for the knowledge base (scripts/build-knowledge-pdf.ts).
 * Pure text generation — the routes and `npm run feedback:export` both use it.
 */
import type { CallResult, Feedback } from "../types.js";

export type Line = { role: "agent" | "prospect"; text: string; state: string };

/** A call as a list of lines: its saved turns, or (older calls) its transcript text. */
export function callLines(call: CallResult): Line[] {
  if (call.turns?.length) return call.turns.map((t) => ({ role: t.role, text: t.text, state: t.state }));
  return call.full_transcript
    .split("\n")
    .map((l) => l.trim())
    .filter(Boolean)
    .map((l) => ({
      role: /^agent:/i.test(l) ? ("agent" as const) : ("prospect" as const),
      text: l.replace(/^(agent|prospect):\s*/i, ""),
      state: "unknown",
    }));
}

const ISSUE_LABEL: Record<Feedback["issue"], string> = {
  wrong_answer: "Wrong answer",
  made_up: "Made up a fact",
  awkward: "Awkward / unnatural",
  misheard: "Misheard the caller",
  too_long: "Too long",
  missing_answer: "Had no answer",
  other: "Other",
};
export const issueLabel = (issue: Feedback["issue"]) => ISSUE_LABEL[issue];

const q = (text: string) => JSON.stringify(text);
const oneLine = (text: string) => text.replace(/\s+/g, " ").trim();

/** Beats a test can start from. Anything else (older calls) starts at the discovery question. */
const KNOWN_STATES = new Set(["OPENING", "CONTEXT_BRIDGE", "PITCH", "OBJECTION_HANDLING", "CLOSE"]);

export function feedbackTests(items: Feedback[]): string {
  const cases = items.map((f) => {
    const state = KNOWN_STATES.has(f.state) ? f.state : "CONTEXT_BRIDGE";
    return `  // ${issueLabel(f.issue)} — reported ${f.created_at.slice(0, 10)}${f.state === "unknown" ? " (older call: beat unknown, starting at discovery)" : ""}
  // Bad reply: ${oneLine(f.agent_text)}
${f.expected ? `  // Should have said: ${oneLine(f.expected)}\n` : ""}  it.skip(${q(`[${f.issue}] at ${state}: caller said "${oneLine(f.caller_text).slice(0, 60)}"`)}, async () => {
    const session = sessionAt(${q(state)});
    const result = await handleTurn(session, ${q(f.caller_text)});
    expect(result.agent).not.toBe(${q(f.agent_text)});
  });`;
  });

  return `// Generated by \`npm run feedback:export\` from "this reply was bad" reports — do not edit by hand.
//
// Every case starts as it.skip: it records a reply a reviewer marked as bad. Fix the behaviour,
// change it.skip to it, and from then on the test guards it. (The LLM and the PDF lookup are
// stubbed here, so these cover the scripted conversation engine, not model wording.)
import { describe, expect, it, vi } from "vitest";
import { createSession } from "../../backend/conversation/stateMachine.js";
import { handleTurn } from "../../backend/conversation/turn.js";
import type { CallState, Lead } from "../../backend/types.js";

vi.mock("../../backend/llm/groq.js", () => ({
  classifyIntent: async () => "unclear",
  naturalizeReply: async (_session: unknown, _text: string, canned: string) => canned,
  steerBackToScript: async () => null,
}));
vi.mock("../../backend/rag/answer.js", () => ({
  answerFromPdf: async () => null,
  lastRetrievalScore: () => 0,
}));

const lead: Lead = {
  company_name: "Example Store",
  contact_name: "Test Caller",
  contact_number: "+919800000099",
  contact_role: "",
  company_domain: "",
  company_description: "",
  industry: "retail",
  need_for_bot: "",
  preferred_language: "hi-IN-hinglish",
  lead_source: "",
  priority_tier: "normal",
  gender: "male",
};

function sessionAt(state: string) {
  const session = createSession(lead);
  session.state = state as CallState;
  if (state === "OPENING") session.openingStage = "intro";
  return session;
}

describe("replies reviewers marked as bad", () => {
${cases.join("\n\n") || "  it.todo(\"no reports yet\");"}
});
`;
}

/** Q&A lines in the shape scripts/build-knowledge-pdf.ts expects, for questions the agent got wrong. */
export function feedbackKnowledge(items: Feedback[]): string {
  const rows = items.filter((f) => f.expected.trim() && ["missing_answer", "wrong_answer", "made_up"].includes(f.issue));
  if (!rows.length) return "// No reports with a corrected answer yet.\n";
  // A JS template literal: escape backslashes, backticks and ${ so any caller text stays valid code.
  const tpl = (text: string) => "`" + oneLine(text).replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$\{/g, "\\${") + "`";
  return (
    `// Paste these into a section's qa: [...] list in scripts/build-knowledge-pdf.ts,\n` +
    `// then run: npm run kb:build && npm run ingest\n` +
    rows.map((f) => `[${tpl(f.caller_text)}, ${tpl(f.expected)}],`).join("\n") +
    "\n"
  );
}
